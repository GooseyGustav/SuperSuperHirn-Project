import random

from app.ports.driven.for_getting_moves.for_getting_codemaker_move import ForGettingCodemakerMove


class CpuCodemaker(ForGettingCodemakerMove):
    """
    CPU implementation of the Codemaker role in the game engine.

    This adapter is responsible for:
    - generating a secret code for a new game
    - producing feedback for a given guess compared to the secret code

    It is connected to the core game engine via the ForGettingCodemakerMove port

    Win condition:
    - If the feedback consists entirely of 8s (i.e., [8, 8, 8, 8, 8]),
      the guess fully matches the secret code and the codebreaker wins.

    Note:
    - The mapping of colors to integers is defined in:
      /src/app/game_model/color_code/color.py
    """

    CODE_LENGTH = 5
    MIN_COLOR = 1
    MAX_COLOR = 8

    BLACK_PEG = 8
    WHITE_PEG = 7

    def get_secret_code(self) -> list[int]:
        """
        Generates a secret code for a new game.
            - A secret code consists of 5 integers
            - Each integer represents a color ID in the range 1-8 (inclusive)
            - A guess is evaluated against the secret code to produce feedback

        Returns:
            list[int]: A list of exactly 5 integers, each in the range 1-8 representing the hidden color sequence.
        """

        return [
            random.randint(self.MIN_COLOR, self.MAX_COLOR)
            for _ in range(self.CODE_LENGTH)
        ]

    def get_feedback(self, secret: list[int], guess: list[int]) -> list[int]:
        """
        Compares a guess against the secret code and generates feedback.
            - 8 (black peg): correct color in the correct position
            - 7 (white peg): correct color in the wrong position
        Each position is evaluated independently. The order of feedback doesn't allow any traceback to the secret code.

        Args:
            secret (list[int]): The secret code generated by this codemaker.
            guess (list[int]): The player's guessed code.

        Returns:
            list[int]: A list of max length 5 containing:
                - 8 for correct color in correct position (black peg)
                - 7 for correct color in wrong position (white peg)
        """

        secret_remaining = []
        guess_remaining = []

        black_pegs = 0
        # Calculate black pegs by iterating over the secret and guess and only save remaining values.
        for s, g in zip(secret, guess):
            if s == g:
                black_pegs += 1
            else:
                secret_remaining.append(s)
                guess_remaining.append(g)

        white_pegs = 0
        secret_counts = {}
        # Summarize how often a color_id is present in the remaining list.
        for s in secret_remaining:
            secret_counts[s] = secret_counts.get(s, 0) + 1

        # Count white pegs based on the guess and remaining secret code colors.
        for g in guess_remaining:
            if secret_counts.get(g, 0) > 0:
                white_pegs += 1
                secret_counts[g] -= 1

        feedback = [self.BLACK_PEG] * black_pegs + [self.WHITE_PEG] * white_pegs
        return feedback
